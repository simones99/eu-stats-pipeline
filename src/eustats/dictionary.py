"""Data dictionary generated from the dbt manifest and the warehouse column types."""

from __future__ import annotations

import json
from pathlib import Path

import duckdb

DOCUMENTED_SCHEMAS = ("marts", "staging")


def build_dictionary(manifest_path: Path, warehouse: Path) -> str:
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    with duckdb.connect(str(warehouse), read_only=True) as con:
        types = {
            (schema, table, column): data_type
            for schema, table, column, data_type in con.execute(
                "select table_schema, table_name, column_name, data_type "
                "from information_schema.columns"
            ).fetchall()
        }

    models = sorted(
        (node for node in manifest["nodes"].values() if node["resource_type"] == "model"),
        key=lambda node: (DOCUMENTED_SCHEMAS.index(node["schema"]), node["name"]),
    )
    lines = [
        "# Data dictionary",
        "",
        "Generated by `eustats report` from the dbt project. Marts are the tables meant for "
        "analysis; staging models are typed views over the raw files.",
        "",
    ]
    for node in models:
        schema, name = node["schema"], node["name"]
        lines += [
            f"## `{schema}.{name}`",
            "",
            " ".join(node.get("description", "").split()) or "_No description._",
            "",
            "| Column | Type | Description |",
            "|---|---|---|",
        ]
        for column, meta in node["columns"].items():
            data_type = types.get((schema, name, column), "")
            description = " ".join(meta.get("description", "").split())
            lines.append(f"| `{column}` | {data_type} | {description} |")
        lines.append("")
    return "\n".join(lines)


def write_dictionary(manifest_path: Path, warehouse: Path, output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(build_dictionary(manifest_path, warehouse), encoding="utf-8")
